#!/usr/bin/env bash
# Fixture tests for the review-load budget. No network or token required.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
CHECK="$ROOT/infra/scripts/ci/pr-size-check.sh"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

pass() { echo "ok: $*"; }
fail() { echo "FAIL: $*" >&2; exit 1; }

fixture() {
  local name="$1" arr="$2" commits="${3:-3}"
  jq -nc --argjson a "$arr" --argjson c "$commits" \
    '{files:$a, commits:$c}' > "$tmp/$name.json"
  printf '%s' "$tmp/$name.json"
}

ok="$(fixture ok '[{"path":"src/a.sh","added":100,"deleted":20,"size":2000}]')"
lock="$(fixture lock '[{"path":"package-lock.json","added":"-","deleted":"-","size":900000},{"path":"package.json","added":10,"deleted":2,"size":300}]')"
many_files="$(fixture files "$(jq -nc '[range(51) | {path:("src/f\(.).sh"),added:1,deleted:0,size:100}]')")"
many_lines="$(fixture lines '[{"path":"src/a.sh","added":501,"deleted":0,"size":20000}]')"
large_file="$(fixture large '[{"path":"src/a.sh","added":251,"deleted":0,"size":20000}]')"
many_gen="$(fixture gen "$(jq -nc '[range(11) | {path:("src/generated/f\(.).go"),added:0,deleted:0,size:100}]')")"
big_gen="$(fixture biggen '[{"path":"src/generated/a.go","added":0,"deleted":0,"size":10485761}]')"
many_bin="$(fixture bin "$(jq -nc '[range(21) | {path:("assets/f\(.).pdf"),added:"-",deleted:"-",size:1000}]')")"
big_bin="$(fixture bigbin '[{"path":"assets/a.pdf","added":"-","deleted":"-","size":10485761}]')"
total_bin="$(fixture totalbin "$(jq -nc '[range(6) | {path:("assets/f\(.).pdf"),added:"-",deleted:"-","size":10485760}]')")"
added="$(fixture added '[{"path":"src/a.sh","added":1,"deleted":0,"size":62914561}]')"
commits="$(fixture commits '[{"path":"src/a.sh","added":1,"deleted":0,"size":100}]' 11)"
data_cfg="$tmp/data.json"
printf '%s\n' '{"pull_request_limits":{"data_patterns":["src/data/**"],"max_data_files":2,"max_data_bytes":1000}}' > "$data_cfg"
data_over="$(fixture dataover '[{"path":"src/data/a.csv","added":10,"deleted":0,"size":600},{"path":"src/data/b.csv","added":10,"deleted":0,"size":600}]')"
override="$tmp/override.json"
printf '%s\n' '{"pull_request_limits":{"max_files_changed":60}}' > "$override"

allow() {
  local name="$1" fix="$2" cfg="${3:-}"
  local args=(--repo test/repo --fixture "$fix")
  [[ -n "$cfg" ]] && args+=(--repo-config "$cfg")
  "$CHECK" "${args[@]}" >/dev/null 2>&1 || fail "$name should allow"
  pass "$name"
}
deny() {
  local name="$1" fix="$2" cfg="${3:-}"
  local args=(--repo test/repo --fixture "$fix")
  [[ -n "$cfg" ]] && args+=(--repo-config "$cfg")
  "$CHECK" "${args[@]}" >/dev/null 2>&1 && fail "$name should deny"
  pass "$name"
}

allow "within budget" "$ok"
allow "lockfile excluded from reviewable lines" "$lock"
deny "too many files" "$many_files"
deny "too many reviewable lines" "$many_lines"
deny "reviewable file too large" "$large_file"
deny "too many generated files" "$many_gen"
deny "generated bytes too large" "$big_gen"
deny "too many binaries" "$many_bin"
deny "binary file too large" "$big_bin"
deny "binary total too large" "$total_bin"
deny "added bytes too large" "$added"
deny "too many commits" "$commits"
deny "data bytes too large" "$data_over" "$data_cfg"
allow "repo override raises file cap" "$many_files" "$override"

echo "pr-size-check tests ok"
